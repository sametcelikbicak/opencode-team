#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates docs/reference/*.md from agents/, commands/, skills/ and team.yaml.
# Stdlib only, deterministic. Run: ruby scripts/generate-reference.rb

require "fileutils"
require "yaml"

ROOT = File.expand_path("..", __dir__)
OUT = File.join(ROOT, "docs", "reference")
HEADER = "<!-- Generated by scripts/generate-reference.rb from the manifests. Do not edit by hand. -->"

def frontmatter(path)
  match = File.read(path).match(/\A---\r?\n(.*?)\r?\n---\r?\n/m)
  raise "#{path}: missing frontmatter" unless match

  YAML.safe_load(match[1], permitted_classes: [], aliases: false) || {}
end

def cell(value)
  value.to_s.strip.gsub("|", "\\|").gsub(/\s+/, " ")
end

def code(value)
  value.nil? || value.to_s.empty? ? "—" : "`#{cell(value)}`"
end

def table(headers, rows)
  lines = []
  lines << "| #{headers.join(' | ')} |"
  lines << "| #{headers.map { '---' }.join(' | ')} |"
  rows.each { |row| lines << "| #{row.join(' | ')} |" }
  lines.join("\n")
end

def write_page(name, title, intro, body)
  FileUtils.mkdir_p(OUT)
  content = <<~MD
    #{HEADER}

    # #{title}

    #{intro}

    #{body}
  MD
  File.write(File.join(OUT, name), content)
end

agents = Dir[File.join(ROOT, "agents/*.md")].sort.map do |path|
  fm = frontmatter(path)
  [code(fm["name"]), cell(fm["description"]), code(fm["mode"]), code(fm["model"])]
end

commands = Dir[File.join(ROOT, "commands/*.md")].sort.map do |path|
  fm = frontmatter(path)
  ["`/#{cell(fm['name'])}`", cell(fm["description"]), code(fm["agent"])]
end

skills = Dir[File.join(ROOT, "skills/*/SKILL.md")].sort.map do |path|
  fm = frontmatter(path)
  [code(fm["name"]), cell(fm["description"])]
end

team = YAML.safe_load(File.read(File.join(ROOT, "team.yaml")), permitted_classes: [], aliases: false) || {}
stages = Array(team["stages"]).map do |stage|
  support = Array(stage["support"])
  [
    code(stage["id"]),
    cell(stage["title"]),
    code(stage["agent"]),
    stage["gate"] ? "yes" : "no",
    code(stage["output"]),
    support.empty? ? "—" : support.map { |agent| "`#{cell(agent)}`" }.join(", ")
  ]
end

write_page(
  "agents.md",
  "Agent reference",
  "The #{agents.size} agent roles defined in `agents/*.md`. Edit the agent file, not this page.",
  table(%w[Agent Description Mode Model], agents)
)

write_page(
  "commands.md",
  "Command reference",
  "The #{commands.size} slash commands defined in `commands/*.md`. Edit the command file, not this page.",
  table(%w[Command Description Agent], commands)
)

write_page(
  "skills.md",
  "Skill reference",
  "The #{skills.size} skills defined in `skills/*/SKILL.md`. Edit the skill file, not this page.",
  table(%w[Skill Description], skills)
)

write_page(
  "stages.md",
  "Stage reference",
  "The #{stages.size} pipeline stages defined in `team.yaml`, in pipeline order. Edit `team.yaml`, not this page.",
  table(%w[Stage Title Agent Gate Output Support], stages)
)

puts "generate-reference: #{agents.size} agents, #{commands.size} commands, #{skills.size} skills, #{stages.size} stages"
